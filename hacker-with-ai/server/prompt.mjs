// セッション参加プロンプトの生成。
// 参加画面に表示され、ユーザがコピーして自分の AI に貼ると、AI がセッションに参加する。
// 設計（2026-11-27 簡素化で確定）：
//   - brief は1本だけ（POST /ai/brief）。事件が切り替わっても取り先は同じで、
//     プレイヤーが「次の事件だよ」と声をかけたら相方が取り直すだけ。乗り換え手順は無い。
//   - brief の取得は GET（curl -s）。一度 POST 専用化したが、道具を持たない AI
//     （ChatGPT 等）が参加自体できなくなるため取りやめた。GET だとプレイヤーが
//     アドレスバーから相方側の情報を覗ける欠点は残るが、遊べることを優先した
//     （2026-11-27 ユーザー判断）。
//   - 参加プロンプトは、PoC（escape-with-ai）の「接続のしかた」方式に戻した
//     （2026-11-27 ユーザー指示）。最初の一手は「まず curl を実行してみる」で、
//     考え込ませない・小細工させない言い切りまで含めて PoC の文面をほぼ移植。
//     ルール（合言葉・用語・ヒント・お祝い）もプロンプトに自己完結で載せる。
//     brief の冒頭の PARTNER_GUIDE は、サーバー側で更新できる正本として併置する。
//   - POST もコマンド実行もできない AI には、プレイヤーが brief の本文を貼る経路がある。
// 作法は escape-with-ai（PoC）を継承：
//   - POST できない環境の件は握りつぶす（プレイヤーに伝えない）
//   - 接続失敗の報告は短く。ネットワーク設定変更をプレイヤーに求めない
//   - Gemini / Perplexity は一行で ChatGPT へ案内
// このゲーム固有の追加：合言葉は「ゲームのヒント：」に加えて「ゲームの用語：」。

