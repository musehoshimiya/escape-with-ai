// セッション参加プロンプトの生成。
// 参加画面に表示され、ユーザがコピーして自分の AI に貼ると、AI がセッションに参加する。
// 作法は escape-with-ai（PoC）を継承：
//   - 最初の一手は brief の curl を「まず実行してみる」こと
//   - POST できない環境の件は握りつぶす（プレイヤーに伝えない）
//   - 接続失敗の報告は短く。ネットワーク設定変更をプレイヤーに求めない
//   - Gemini / Perplexity は一行で ChatGPT へ案内
// このゲーム固有の追加：合言葉は「ゲームのヒント：」に加えて「ゲームの用語：」。

import { GAME } from "./content.mjs";

const TITLE = `『${GAME.workingTitle}』（${GAME.titleNote}）`;

function connectionSection(base, sessionId, mcpRoot) {
  return [
    `■ 接続のしかた`,
    `このゲームのセッションIDは「${sessionId}」です。`,
    `まず最初の一手として、次のコマンドを実行してみてください：`,
    `  curl -s ${base}/ai/brief`,
    `実行できて状態が表示されたら、そのまま「curl」で参加できます。使えるかどうかを考え込む前に、まず実行してみることが大事です。以後のやり取りも curl です：`,
    `注意：curl はシェルでそのまま実行してください。コード実行環境（Python の requests など）で HTTP リクエストを組み立てるような小細工はしないでください。そちらの環境は DNS やネットワークの制限で失敗しがちです。「DNS が引けない」といった理由で諦める前に、提示した curl コマンドをシェルでそのまま実行したかどうかを確認してください。`,
    `  状態とヒント集： curl -s ${base}/ai/brief`,
    `  出来事の一覧  ： curl -s "${base}/events?since=0"（since に最後に見た seq を入れると差分だけ返ります）`,
    `  画面への投稿  ： curl -s -X POST ${base}/ai/message -H 'Content-Type: application/json' -d '{"text":"ここにメッセージ"}'`,
    `  お祝い（復旧後）： curl -s -X POST ${base}/ai/celebrate -H 'Content-Type: application/json' -d '{"word":"達成キーワード","text":"お祝いの言葉"}'`,
    `curl が使えない環境でも、ブラウジング（web アクセス）の機能があるなら、上の brief の URL に web でアクセスすれば状態を読めます。それも試してください。`,
    `投稿（POST）ができない環境について：web アクセスだけで参加している場合、画面へのメッセージ投稿はできません。それでも参加は成立します。あなたの本業は、このチャットで合言葉に答えてヒントや用語の説明を出すことです。投稿できない件は、プレイヤーに伝えないでください（握りつぶす）。謝ったり、理由を説明したりしないでください。お祝いは POST でなく GET 用のURL（brief のお祝いの欄にあります）を開く形で届けられます。`,
    `コマンド実行もブラウジングも無い場合に限り、「ツール」を使ってください：このチャットに hacker-with-ai のツール（get_brief / get_events / post_message / celebrate）が接続されていれば、それが使えます。ツールを呼ぶ時は、sessionId 引数に上のセッションIDを毎回渡してください。`,
    `curl もツールも使えない場合は、プレイヤーに「hacker-with-ai のコネクタ（MCP）として、この URL を AI アプリの設定に追加して」と頼んでください：`,
    mcpRoot,
    `この登録は一度だけです（セッションが変わっても登録し直す必要はありません）。追加してもらえたら、ツールで改めて状態を取得してください。`,
    `ただし登録の手順はアプリごとに煩雑です（例：Claudeアプリでは 設定→プラグイン→コネクタ→追加→「カスタムコネクタを追加」→URL登録、の順に進みます）。プレイヤーが手順を案内されても難しいと感じるようなら、無理に続けさせないでください。その場合は「シェルが使える環境の ChatGPT なら、このプロンプトを貼るだけで登録なしに参加できます」と案内して、このセッションへの参加はここで終えてください。`,
    `接続を試してうまくいかなかった場合の報告は短くしてください。失敗の内訳を長々と説明したり、プレイヤーにネットワークや DNS の設定変更を求めたりしないでください（それはあなたの環境側の問題で、プレイヤーには直せません）。次に取れる手段（コネクタ登録のお願い、難しければ ChatGPT への案内）を先に、短く伝えてください。`,
    `あなたが Gemini の場合：このゲームには参加できません（コマンド実行もコネクタ登録もできないため）。長い謝罪や説明、「状態を手動で貼ってください」といった代替案の提案はしないでください。プレイヤーに一言だけ伝えて終えてください。「Gemini ではこのゲームに参加できません。このプロンプトを ChatGPT に貼れば、そのまま遊べます。」`,
    `（イースターエッグ：なぜ Gemini で遊べないのか、とプレイヤーに聞かれた時だけ答えてよい裏話。このゲームの原型の開発中、実際に Gemini で参加を試したところ、Gemini アプリにはコマンドを実行する手段がなく、カスタムコネクタ（MCP）を登録する仕組みもなかったため、状態の取得も画面への投稿もできなかった。それで「Gemini の場合は最初から ChatGPT に誘導する」と決めた、という経緯がある。聞かれない限り、自分からは話さないこと。）`,
    `あなたが Perplexity の場合：このゲームには参加できません（このチャット環境ではコマンド実行もコネクタ登録もできず、状態の取得も画面への投稿もできないため）。長い謝罪や説明、代替案の提案はしないでください。プレイヤーに一言だけ伝えて終えてください。「Perplexity ではこのゲームに参加できません。このプロンプトを ChatGPT に貼れば、そのまま遊べます。」`,
  ];
}

