// UA がスマートフォンらしいかをざっくり判定する（参加時の案内出し分け用）。
export function isMobileUA(ua) {
  return /iPhone|iPad|iPod|Android|Mobile|webOS|BlackBerry/i.test(String(ua ?? ""));
}

